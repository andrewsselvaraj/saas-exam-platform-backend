import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Converts the phpMyAdmin dump in sql/ into an H2 Flyway seed migration.
 *
 * Only the hierarchy tables (org, class, subject, chapter, question v2, answer v2) and exam_info are kept.
 * User/admin/role tables and scratch tables are ignored. Rows whose parents are missing are dropped
 * so that the foreign keys can be enforced, and placeholder chapter ids ('None', '') become NULL.
 *
 * Usage (JDK 17+, from the project root):
 *   java tools/MysqlDumpToH2.java sql/m2itssql_complete.sql src/main/resources/db/migration/V2__seed_data.sql
 */
public class MysqlDumpToH2 {

    public static void main(String[] args) throws IOException {
        Path in = Path.of(args.length > 0 ? args[0] : "sql/m2itssql_complete.sql");
        Path out = Path.of(args.length > 1 ? args[1] : "src/main/resources/db/migration/V2__seed_data.sql");
        String dump = Files.readString(in, StandardCharsets.UTF_8);

        Map<String, Table> tables = parseInserts(dump);
        Table orgs = tables.get("org_info");
        Table classes = tables.get("class_info");
        Table subjects = tables.get("subject_info");
        Table chapters = tables.get("chapter_info");
        Table questions = tables.get("question_info_v_two");
        Table answers = tables.get("answer_info_v_two");
        Table exams = tables.get("exam_info");

        Set<String> orgIds = ids(orgs, "pk_org_id");
        classes.rows.removeIf(r -> !orgIds.contains(classes.get(r, "fk_org_id")));
        Set<String> classIds = ids(classes, "pk_class_id");
        subjects.rows.removeIf(r -> !classIds.contains(subjects.get(r, "fk_class_id"))
                || !orgIds.contains(subjects.get(r, "fk_org_id")));
        Set<String> subjectIds = ids(subjects, "pk_subject_id");
        chapters.rows.removeIf(r -> !subjectIds.contains(chapters.get(r, "fk_subject_id"))
                || !classIds.contains(chapters.get(r, "fk_class_id"))
                || !orgIds.contains(chapters.get(r, "fk_org_id")));
        Set<String> chapterIds = ids(chapters, "pk_chapter_id");

        questions.rows.removeIf(r -> !subjectIds.contains(questions.get(r, "fk_subject_id"))
                || !classIds.contains(questions.get(r, "fk_class_id"))
                || !orgIds.contains(questions.get(r, "fk_org_id")));
        nullUnknown(questions, "fk_chapter_id", chapterIds);
        Set<String> questionIds = ids(questions, "pk_question_id");

        answers.rows.removeIf(r -> !questionIds.contains(answers.get(r, "fk_question_id"))
                || !subjectIds.contains(answers.get(r, "fk_subject_id"))
                || !classIds.contains(answers.get(r, "fk_class_id"))
                || !orgIds.contains(answers.get(r, "fk_org_id")));
        nullUnknown(answers, "fk_chapter_id", chapterIds);
        Set<String> answerIds = ids(answers, "pk_answer_id");

        exams.rows.removeIf(r -> !questionIds.contains(exams.get(r, "fk_question_id"))
                || !answerIds.contains(exams.get(r, "fk_user_selected_answer_id"))
                || !subjectIds.contains(exams.get(r, "fk_subject_id"))
                || !classIds.contains(exams.get(r, "fk_class_id"))
                || !orgIds.contains(exams.get(r, "fk_org_id")));

        StringBuilder sb = new StringBuilder();
        sb.append("-- GENERATED by tools/MysqlDumpToH2.java from ").append(in.getFileName()).append(". Do not edit by hand.\n\n");
        write(sb, orgs, "org_info");
        write(sb, classes, "class_info");
        write(sb, subjects, "subject_info");
        write(sb, chapters, "chapter_info");
        write(sb, questions, "question_info");
        write(sb, answers, "answer_info");
        write(sb, exams, "exam_info");
        Files.createDirectories(out.getParent());
        Files.writeString(out, sb.toString(), StandardCharsets.UTF_8);
    }

    static final class Table {
        final List<String> columns;
        final List<List<String>> rows = new ArrayList<>();

        Table(List<String> columns) {
            this.columns = columns;
        }

        String get(List<String> row, String column) {
            return row.get(columns.indexOf(column));
        }

        void set(List<String> row, String column, String value) {
            row.set(columns.indexOf(column), value);
        }
    }

    static Set<String> ids(Table t, String column) {
        Set<String> ids = new HashSet<>();
        for (List<String> r : t.rows) ids.add(t.get(r, column));
        return ids;
    }

    static void nullUnknown(Table t, String column, Set<String> known) {
        for (List<String> r : t.rows) {
            if (!known.contains(t.get(r, column))) t.set(r, column, null);
        }
    }

    static void write(StringBuilder sb, Table t, String targetTable) {
        sb.append("-- ").append(targetTable).append(": ").append(t.rows.size()).append(" rows\n");
        String header = "INSERT INTO " + targetTable + " (" + String.join(", ", t.columns) + ") VALUES\n";
        int batch = 200;
        for (int i = 0; i < t.rows.size(); i += batch) {
            sb.append(header);
            List<List<String>> chunk = t.rows.subList(i, Math.min(i + batch, t.rows.size()));
            for (int j = 0; j < chunk.size(); j++) {
                sb.append('(');
                List<String> row = chunk.get(j);
                for (int k = 0; k < row.size(); k++) {
                    if (k > 0) sb.append(", ");
                    String v = row.get(k);
                    sb.append(v == null ? "NULL" : "'" + v.replace("'", "''") + "'");
                }
                sb.append(j == chunk.size() - 1 ? ");\n" : "),\n");
            }
        }
        sb.append('\n');
    }

    /** Parses every {@code INSERT INTO `t` (cols) VALUES (...),(...);} statement, unescaping MySQL string literals. */
    static Map<String, Table> parseInserts(String sql) {
        Map<String, Table> tables = new LinkedHashMap<>();
        String marker = "INSERT INTO `";
        int pos = 0;
        while ((pos = sql.indexOf(marker, pos)) >= 0) {
            int nameEnd = sql.indexOf('`', pos + marker.length());
            String name = sql.substring(pos + marker.length(), nameEnd);
            int colStart = sql.indexOf('(', nameEnd);
            int colEnd = sql.indexOf(')', colStart);
            List<String> cols = new ArrayList<>();
            for (String c : sql.substring(colStart + 1, colEnd).split(",")) cols.add(c.trim().replace("`", ""));
            Table table = tables.computeIfAbsent(name, n -> new Table(cols));

            int i = sql.indexOf("VALUES", colEnd) + "VALUES".length();
            while (true) {
                while (Character.isWhitespace(sql.charAt(i)) || sql.charAt(i) == ',') i++;
                if (sql.charAt(i) == ';') break;
                if (sql.charAt(i) != '(') throw new IllegalStateException("Expected '(' at " + i + " in " + name);
                i++;
                List<String> row = new ArrayList<>();
                while (true) {
                    while (Character.isWhitespace(sql.charAt(i))) i++;
                    char c = sql.charAt(i);
                    if (c == '\'') {
                        StringBuilder v = new StringBuilder();
                        i++;
                        while (true) {
                            char ch = sql.charAt(i);
                            if (ch == '\\') {
                                char e = sql.charAt(i + 1);
                                v.append(switch (e) {
                                    case 'n' -> '\n';
                                    case 'r' -> '\r';
                                    case 't' -> '\t';
                                    case '0' -> '\0';
                                    case 'Z' -> (char) 26;
                                    default -> e;
                                });
                                i += 2;
                            } else if (ch == '\'' && sql.charAt(i + 1) == '\'') {
                                v.append('\'');
                                i += 2;
                            } else if (ch == '\'') {
                                i++;
                                break;
                            } else {
                                v.append(ch);
                                i++;
                            }
                        }
                        row.add(v.toString());
                    } else {
                        int start = i;
                        while (sql.charAt(i) != ',' && sql.charAt(i) != ')') i++;
                        String raw = sql.substring(start, i).trim();
                        row.add(raw.equalsIgnoreCase("NULL") ? null : raw);
                    }
                    while (Character.isWhitespace(sql.charAt(i))) i++;
                    if (sql.charAt(i) == ',') {
                        i++;
                    } else if (sql.charAt(i) == ')') {
                        i++;
                        break;
                    }
                }
                if (row.size() != cols.size()) throw new IllegalStateException("Column mismatch in " + name);
                table.rows.add(row);
            }
            pos = i;
        }
        return tables;
    }
}
